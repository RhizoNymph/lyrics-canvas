#!/usr/bin/env python3
"""Copy the backend's score reference into lcxlib/score_ref/ (docs/features/score_backend.md#agent).

lcx is stdlib-only and installed by symlink, so it cannot import the backend package (whose
``app.services.score`` imports pydantic). The modules lcx needs (validate, timing, rest link, text
splice and what they import) are pure stdlib; this script copies them verbatim, rewriting only the
import prefixes, and writes a small ``__init__.py``. ``tests/test_score_ref.py`` fails when the copy is
out of date. Run from the repo root or anywhere: ``python tools/agent/scripts/vendor_score_ref.py``.
"""

from __future__ import annotations

import sys
from pathlib import Path

AGENT_DIR = Path(__file__).resolve().parent.parent
REPO = AGENT_DIR.parent.parent
SOURCE = REPO / "backend" / "app" / "services"
TARGET = AGENT_DIR / "lcxlib" / "score_ref"

# backend path relative to SOURCE -> vendored file name
MODULES: dict[str, str] = {
    "score/constants.py": "constants.py",
    "score/errors.py": "errors.py",
    "score/types.py": "types.py",
    "score/codec.py": "codec.py",
    "score/validate.py": "validate.py",
    "score/grid_view.py": "grid_view.py",
    "score/timing.py": "timing.py",
    "score/rest_link.py": "rest_link.py",
    "score/text.py": "text.py",
    "rest_marks.py": "rest_marks.py",
}

HEADER = "# GENERATED by tools/agent/scripts/vendor_score_ref.py from backend/app/services/{src}; do not edit.\n"

INIT = '''# GENERATED by tools/agent/scripts/vendor_score_ref.py; do not edit.
"""The backend's score reference (spec/score_format.md), vendored for lcx: validate, timing, the rest
link and the text splice. Same code as backend/app/services/score/, minus the pydantic wire model."""

from lcxlib.score_ref.codec import score_to_json
from lcxlib.score_ref.errors import ScoreError, ScoreInvalid, ScoreReason, ScoreTextMismatch
from lcxlib.score_ref.rest_link import apply_rest_link
from lcxlib.score_ref.text import changed_line_texts, splice_line_texts
from lcxlib.score_ref.timing import PICKUP_BAR, bar_at_tick, bar_start_tick, beat_unit, meter_at_tick
from lcxlib.score_ref.types import Score
from lcxlib.score_ref.validate import Invalid, Valid, check_score, validate

__all__ = [
    "Invalid", "PICKUP_BAR", "Score", "ScoreError", "ScoreInvalid", "ScoreReason", "ScoreTextMismatch", "Valid",
    "apply_rest_link", "bar_at_tick", "bar_start_tick", "beat_unit", "changed_line_texts", "check_score",
    "meter_at_tick", "score_to_json", "splice_line_texts", "validate",
]
'''


def vendored(src: str) -> str:
    text = (SOURCE / src).read_text(encoding="utf-8")
    text = text.replace("from app.services.score.", "from lcxlib.score_ref.")
    text = text.replace("from app.services.rest_marks import", "from lcxlib.score_ref.rest_marks import")
    if "app.services" in text:
        raise SystemExit(f"{src}: an import the vendoring does not rewrite is left")
    return HEADER.format(src=src) + text


def render() -> dict[str, str]:
    """Vendored file name -> content."""
    return {"__init__.py": INIT, **{name: vendored(src) for src, name in MODULES.items()}}


def main() -> int:
    TARGET.mkdir(exist_ok=True)
    for name, content in render().items():
        (TARGET / name).write_text(content, encoding="utf-8")
    print(f"wrote {len(MODULES) + 1} files to {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
